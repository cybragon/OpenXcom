#!/usr/bin/env python3
"""Generates src/Engine/HiResHqxGL.h: the hq2x/hq3x/hq4x pattern -> output-pixel recipe table (from the switch statements in
src/Engine/Scalers/hq?x.cpp) as a texture image for the GLSL port. Usage: gen_hqx_lut.py <Scalers dir> <out header>"""
import re, sys
d = sys.argv[1] if len(sys.argv) > 1 else '/workspace/oxce/src/src/Engine/Scalers'
out = sys.argv[2] if len(sys.argv) > 2 else '/workspace/oxce/src/src/Engine/HiResHqxGL.h'
ROWS = {2: 0, 3: 4, 4: 13}
CONDS = {}
def cid(a, b):
    k = (a, b)
    if k not in CONDS: CONDS[k] = len(CONDS) + 1
    return CONDS[k]
lut = [[[0] * 4] * 2 for _ in range(1)]
W = 512; H = 29
img = [0] * (W * H * 4)
hdr = open(d + '/hq2x.cpp').read().split('#include')[0]
for f in (2, 3, 4):
    src = open('%s/hq%dx.cpp' % (d, f)).read()
    macros = {}
    for m in re.finditer(r'#define\s+(PIXEL(\d)(\d)(?:_\w+)?)\s+\*(?:\(dp[^)]*\)|dp)\s*=\s*(.*?);\s*$', src, re.M):
        name, r, c, rhs = m.group(1), int(m.group(2)), int(m.group(3)), m.group(4).strip()
        mi = re.match(r'Interp(\d+)\((.*)\)$', rhs)
        if mi:
            kind = int(mi.group(1)); args = [int(x) for x in re.findall(r'w\[(\d)\]', mi.group(2))]
        else:
            mw = re.match(r'w\[(\d)\]$', rhs); assert mw, rhs
            kind = 0; args = [int(mw.group(1))]
        while len(args) < 3: args.append(0)
        macros[name] = (r, c, kind, args)
    body = src[src.index('switch (pattern)'):]
    lines = [l.strip() for l in body.split('\n')]
    i = 0; cases = {}
    labels = []
    while i < len(lines):
        l = lines[i]; i += 1
        mc = re.match(r'case (\d+):', l)
        if mc: labels.append(int(mc.group(1))); continue
        if l == '{' and labels:
            # case body
            subs = {}   # (r,c) -> {'t':op,'e':op,'cond':id}
            cond = None; branch = None; depth = 0
            while True:
                l = lines[i]; i += 1
                mi = re.match(r'if \(Diff\(w\[(\d)\], w\[(\d)\]\)\)', l)
                if mi: cond = cid(int(mi.group(1)), int(mi.group(2))); branch = 't'; continue
                if l == 'else': branch = 'e'; continue
                if l == '{': depth += 1; continue
                if l == '}':
                    if depth > 0: depth -= 1; 
                    if depth == 0 and branch is not None and cond is not None and lines[i] != 'else': cond = None; branch = None
                    continue
                if l.startswith('break'): break
                if l in macros:
                    r, c, kind, args = macros[l]
                    e = subs.setdefault((r, c), {})
                    op = (kind, args)
                    if cond is None: e['t'] = op; e['e'] = op; e['c'] = 0
                    else:
                        assert e.get('c', cond) in (0, cond) or 't' not in e or True
                        e[branch] = op; e['c'] = cond
                    continue
                if l: raise Exception('unparsed: %s' % l)
            # closing brace of case
            for lab in labels: cases[lab] = subs
            labels = []
    assert len(cases) == 256, (f, len(cases))
    for pat, subs in cases.items():
        assert len(subs) == f * f, (f, pat, len(subs))
        for (r, c), e in subs.items():
            assert 't' in e and 'e' in e, (f, pat, r, c, e)
            row = ROWS[f] + r * f + c
            for t, key in ((0, 't'), (1, 'e')):
                kind, args = e[key]
                px = (row * W + pat * 2 + t) * 4
                img[px] = kind | (e['c'] << 4); img[px + 1] = args[0]; img[px + 2] = args[1]; img[px + 3] = args[2]
print('conds', CONDS)
assert CONDS == {(2, 6): 1, (6, 8): 2, (8, 4): 3, (4, 2): 4}, CONDS
txt = hdr + '''
// Pattern table of the GLSL hqx port (generated by tools/gen_hqx_lut.py from hq2x.cpp / hq3x.cpp / hq4x.cpp, same recipes).
// Texture W=512, H=29, RGBA8: x = pattern*2 + (0: recipe, 1: recipe when the condition is false), y = ROWS[factor] + row*factor + col
// (factor 2: rows 0-3, factor 3: rows 4-12, factor 4: rows 13-28). R = interpolation kind (low nibble: 0 = copy, N = InterpN) |
// condition << 4 (0 none, 1 Diff(w2,w6), 2 Diff(w6,w8), 3 Diff(w8,w4), 4 Diff(w4,w2)); G, B, A = indices (1-9) of the source pixels.
#ifndef OPENXCOM_HIRESHQXGL_H
#define OPENXCOM_HIRESHQXGL_H
namespace OpenXcom
{
namespace
{
const int HQX_LUT_W = 512, HQX_LUT_H = 29;
const unsigned char HQX_LUT[512 * 29 * 4] = {
'''
rows = []
for i in range(0, len(img), 32):
    rows.append(','.join(str(v) for v in img[i:i + 32]))
txt += ',\n'.join(rows) + '\n};\n'
sh = open(d + '/../../../tools/hqx_fs.glsl').read().replace('@TAPS@', open(d + '/../../../tools/glsl_taps.glsl').read())
txt += 'const char *const SM_FS_UP_HQX = R"GLSL(' + sh + ')GLSL";\n}\n}\n#endif\n'
open(out, 'w').write(txt)
print('ok', len(txt))
